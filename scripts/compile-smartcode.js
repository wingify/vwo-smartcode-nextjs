/**
 * Minifies src/smartCodeV22.js and src/smartCodeV30.js and emits
 * src/smartCode.generated.ts for import from VWOScript (no backtick payload).
 */
const fs = require('fs');
const path = require('path');
const { minify } = require('terser');

const ROOT = path.join(__dirname, '..');
const OUTPUT = path.join(ROOT, 'src/smartCode.generated.ts');

const PLACEHOLDERS = {
  accountId: '__VWO_ACCOUNT_ID__',
  settingsTimeout: '__VWO_SETTINGS_TIMEOUT__',
  hideElement: '__VWO_HIDE_ELEMENT__',
  hideElementStyle: '__VWO_HIDE_ELEMENT_STYLE__',
};

const VARIANTS = [
  { name: 'V22', source: path.join(ROOT, 'src/smartCodeV22.js') },
  { name: 'V30', source: path.join(ROOT, 'src/smartCodeV30.js') },
];

async function minifySmartCode(sourcePath) {
  const source = fs.readFileSync(sourcePath, 'utf8');
  const result = await minify(source, {
    compress: { defaults: true, sequences: false },
    mangle: true,
    format: { comments: false },
    module: false,
    ecma: 2015,
  });

  if (result.error) {
    throw result.error;
  }
  if (!result.code) {
    throw new Error(`terser produced empty output for ${sourcePath}`);
  }

  for (const token of Object.values(PLACEHOLDERS)) {
    if (!result.code.includes(token)) {
      throw new Error(
        `Placeholder ${token} missing after minify — check ${sourcePath}`
      );
    }
  }

  return result.code;
}

async function main() {
  const minified = {};
  for (const variant of VARIANTS) {
    minified[variant.name] = await minifySmartCode(variant.source);
    console.log(
      `Minified ${path.relative(ROOT, variant.source)} (${minified[variant.name].length} chars)`
    );
  }

  const out = `/* Generated by scripts/compile-smartcode.js — do not edit. */
export interface SmartCodeParams {
  version: 2.2 | 3.0;
  accountId: string;
  settingsTimeout: number;
  hideElement: string;
  hideElementStyle: string;
}

const SMART_CODE_V22_TEMPLATE = ${JSON.stringify(minified.V22)};
const SMART_CODE_V30_TEMPLATE = ${JSON.stringify(minified.V30)};

export function buildSmartCode(p: SmartCodeParams): string {
  const template =
    p.version === 3.0 ? SMART_CODE_V30_TEMPLATE : SMART_CODE_V22_TEMPLATE;
  return template
    .replace(/${PLACEHOLDERS.accountId}/g, p.accountId)
    .replace(/${PLACEHOLDERS.settingsTimeout}/g, String(p.settingsTimeout))
    .replace(
      /["']${PLACEHOLDERS.hideElement}["']/g,
      JSON.stringify(p.hideElement)
    )
    .replace(
      /["']${PLACEHOLDERS.hideElementStyle}["']/g,
      JSON.stringify(p.hideElementStyle)
    );
}
`;

  fs.writeFileSync(OUTPUT, out);
  console.log(`Wrote ${path.relative(ROOT, OUTPUT)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
